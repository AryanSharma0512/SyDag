const createSpatialGrid = (
  baseYield: number,
  baseNdvi: number,
  baseRain: number,
  soil: string,
  varianceMultiplier: number = 1.0
): SpatialZone[] => {
  const zones: SpatialZone[] = [];
  const rows = 4;
  const cols = 4;

  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      const id = `z-${r * cols + c + 1}`;
      const name = `Zone ${r * cols + c + 1}`;
      // Introduce spatial gradient (e.g. slight depression with higher moisture in row 2, col 2-3)
      const distFromCenter = Math.hypot(r - 1.5, c - 1.5);
      const yieldOffset = Math.sin(r * 1.8 + c * 1.2) * 8.5 * varianceMultiplier - distFromCenter * 2.2;
      const ndviOffset = Math.sin(r * 1.4 + c * 1.7) * 0.05 * varianceMultiplier;
      const rainOffset = (r === 2 && c >= 2 ? 4 : -2);

      const zoneYield = Math.round((baseYield + yieldOffset) * 10) / 10;
      const zoneNdvi = Math.min(0.92, Math.max(0.35, Math.round((baseNdvi + ndviOffset) * 100) / 100));
      const zoneRain = Math.max(15, Math.round(baseRain + rainOffset));

      zones.push({
        id,
        name,
        gridRow: r,
        gridCol: c,
        predictedYield: zoneYield,
        ndvi: zoneNdvi,
        rainfall30Day: zoneRain,
        soil,
        heatStressIndex: Math.round((0.2 + distFromCenter * 0.12) * 100) / 100,
        satelliteReflectance: Math.round((0.18 + zoneNdvi * 0.22) * 100) / 100,
      });
    }
  }
  return zones;
};

